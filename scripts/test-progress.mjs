import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import ts from 'typescript';
import { evaluateDecision, hadEarlyRisk } from '../app/training-rules.js';
const cases=JSON.parse(await readFile('content/generated/cases.json','utf8'));
const client=await readFile('app/game-client.tsx','utf8');
const parser=client.slice(client.indexOf('function readSavedProgress('),client.indexOf('function formatSavedTime('));
assert.ok(parser.length>1000);
const source=ts.transpileModule(parser,{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText;
const context=vm.createContext({cases,evaluateDecision,hadEarlyRisk,verdictValues:['normal','caution','scam'],responseActionValues:['verify','pause','block','report'],confidenceOptions:[50,70,90],locationValues:['home','bank','cafe','police','library'],phoneAppValues:['home','messages']});
vm.runInContext(source,context);
const restore=value=>context.readSavedProgress(typeof value==='string'?value:JSON.stringify(value));
assert.equal(restore('not json'),null);
assert.equal(restore({version:1,results:[],savedAt:Date.now()}),null);
const save={version:2,round:1,savedAt:Date.now(),results:[],evidence:{},verificationHistory:{},riskHistory:{},practice:[],activeIndex:0};
for(const gameCase of cases){
 const clues=gameCase.training.evidence.filter(clue=>clue.key);
 const history=clues.map((clue,index)=>({source:clue.source,evidence:clue.text,minuteOffset:3+index*5}));
 save.evidence[gameCase.id]=clues.map(clue=>clue.text);
 save.verificationHistory[gameCase.id]=history;
 const decision={picked:gameCase.verdict,action:gameCase.training.appropriateActions[0],confidence:90,evidence:save.evidence[gameCase.id],selectedEvidence:save.evidence[gameCase.id],history,riskBeforeEvidence:false};
 save.results.push({...decision,...evaluateDecision(gameCase,decision),caseId:gameCase.id,decisionMinute:10,exposed:false});
 save.activeIndex=save.results.length-1;
 const restored=restore(save);
 assert.ok(restored,'every intermediate save can resume');
 assert.equal(restored.results.length,save.results.length);
 assert.equal(restored.availableCount,Math.min(cases.length,save.results.length+1));
 assert.equal(restored.results.at(-1).score,100);
 assert.equal(restored.round,1);
 assert.ok(!('chats' in restored)&&!('draft' in restored));
}
save.results[0].score=999999;
assert.equal(restore(save).results[0].score,100,'saved score is recomputed');
save.results[0].selectedEvidence.push(save.results[0].selectedEvidence[0]);
assert.equal(restore(save).results[0].selectedEvidence.length,2,'deduplicate selected clues');
save.evidence[cases[0].id]=[];
assert.equal(restore(save).results[0].breakdown.evidence,0,'uncollected selection must not earn credit after resume');
assert.equal(restore(save).results[0].selectedEvidence.length,0);
save.practice=[{caseId:cases[0].id,changed:true,correct:true,northStar:true}];
assert.equal(restore(save).practice.length,1);
const snapshot=client.match(/const snapshot: SavedProgress = \{([\s\S]*?)\n    \};/)[1];
assert.ok(!/\bchats\b|\bdraft\b/.test(snapshot),'free conversation stays out of persistence');
assert.ok(snapshot.includes('riskHistory')&&snapshot.includes('practice'));
console.log('Progress tests passed: all six resume points, old/corrupt saves, recomputed scores, collected-only evidence, isolated practice, no conversation persistence.');
