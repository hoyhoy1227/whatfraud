import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { evaluateDecision, verifiedClaims, hadEarlyRisk, deriveDayState, summarizeTraining, replayCases } from '../app/training-rules.js';
const cases=JSON.parse(await readFile('content/generated/cases.json','utf8'));
assert.equal(cases.length,6);
for(const verdict of ['normal','caution','scam'])assert.equal(cases.filter(item=>item.verdict===verdict).length,2);
const allResults=[];
for(const gameCase of cases) {
 const key=gameCase.training.evidence.filter(clue=>clue.key);
 const history=key.map((clue,i)=>({source:clue.source,evidence:clue.text,minuteOffset:3+i}));
 const decision={picked:gameCase.verdict,action:gameCase.training.appropriateActions[0],confidence:90,evidence:key.map(clue=>clue.text),selectedEvidence:key.map(clue=>clue.text),history,riskBeforeEvidence:false};
 const best=evaluateDecision(gameCase,decision);
 assert.equal(best.score,100);assert.equal(best.northStar,true);
 assert.ok(verifiedClaims(gameCase,decision.evidence).length>=2);
 assert.equal(verifiedClaims(gameCase,gameCase.training.evidence.map(clue=>clue.text)).length,3);
 const uncollected=evaluateDecision(gameCase,{...decision,evidence:[]});
 assert.equal(uncollected.breakdown.evidence,0);assert.equal(uncollected.northStar,false);
 const duplicated=evaluateDecision(gameCase,{...decision,selectedEvidence:[...decision.selectedEvidence,...decision.selectedEvidence]});
 assert.equal(duplicated.score,best.score);
 const wrong=gameCase.verdict==='scam'?'normal':'scam';
 const mistaken=evaluateDecision(gameCase,{...decision,picked:wrong});
 assert.ok(mistaken.feedback.some(text=>text.includes('모순')));
 assert.ok(mistaken.breakdown.confidence<evaluateDecision(gameCase,{...decision,picked:wrong,confidence:50}).breakdown.confidence);
 const neutral=gameCase.training.evidence.find(clue=>!clue.key);
 assert.equal(evaluateDecision(gameCase,{...decision,evidence:[neutral.text],selectedEvidence:[neutral.text]}).breakdown.evidence,0);
 const wandering=evaluateDecision(gameCase,{...decision,history:gameCase.training.evidence.map(clue=>({source:clue.source}))});
 assert.ok(wandering.score<best.score);
 assert.equal(hadEarlyRisk(gameCase,history,[{kind:'link',minuteOffset:2}]),true);
 assert.equal(hadEarlyRisk(gameCase,history,[{kind:'link',minuteOffset:10}]),false);
 allResults.push({...best,...decision,caseId:gameCase.id,riskBeforeEvidence:false,exposed:false});
}
assert.equal(summarizeTraining(allResults,cases).groundedSafety,100);
assert.equal(deriveDayState(allResults,cases,{}).verificationHabit,6);
assert.equal(deriveDayState([],cases,{'paid-market-class':true}).exposed,true);
const replay=replayCases(cases,1);
assert.notEqual(replay[0].sender,cases[0].sender);
assert.deepEqual(replay.map(c=>c.training),cases.map(c=>c.training));
assert.deepEqual(replay.map(c=>c.checks),cases.map(c=>c.checks));
assert.equal(summarizeTraining(allResults,cases,[{changed:true}]).changedAfterReview,100);
console.log('Six-case training tests passed: selected-only evidence, contradictions, calibration, efficiency, branching, metrics, stable replay facts.');

const confirmedButUnselected=evaluateDecision(cases[0],{picked:'normal',action:'verify',confidence:70,evidence:cases[0].training.evidence.filter(clue=>clue.key).map(clue=>clue.text),selectedEvidence:[],history:[]});
assert.equal(confirmedButUnselected.collectedKeyCount,2);
assert.equal(confirmedButUnselected.keyCount,0);
assert.equal(confirmedButUnselected.northStar,false);
