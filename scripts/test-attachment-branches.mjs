import assert from 'node:assert/strict';
import {createRun,transition,serializeRun,restoreRun,totalSpent} from '../app/story/engine.js';
import {canAttach,validateStoryContext,messageAttachment,messageConsequences,friendFollowupLines} from '../app/story/one-shot.js';
const step=(state,type,data='')=>transition(state,{chapter:state.chapter,type,data});
let state=createRun();
assert.equal(canAttach(state,'recipient-note'),false);
state=step(state,'inspect','familiar-request:recipient');
assert.equal(canAttach(state,'recipient-note'),true);
state=step(state,'resolve','paused');
state=step(state,'message-attachment','friend:recipient-note');
assert.equal(messageAttachment(state,'friend'),'recipient-note');
assert.equal(step(state,'message-attachment','friend:account-profile'),state);
state=step(state,'message','friend:together');
state=step(state,'message-style','friend:records:records');
assert.match(friendFollowupLines(state)[0],/한별/);
state=step(state,'message-followup','friend:call');
state=step(state,'message-close','friend');
state=step(state,'next');
assert.equal(state.chapter,1);
assert.equal(canAttach(state,'recipient-note'),false);
assert.equal(step(state,'message-attachment','friend:recipient-note'),state);
assert.deepEqual(restoreRun(serializeRun(state)),state);
assert.equal(totalSpent(state),0);
assert.ok(messageConsequences(state).some(text=>text.includes('수취인')));
assert.equal(validateStoryContext({sceneId:'friend',caseId:'familiar-request',stageId:'arrival',resolved:true,joined:false,attachment:'recipient-note'}),true);
assert.equal(validateStoryContext({sceneId:'friend',caseId:'familiar-request',stageId:'arrival',resolved:true,joined:false,attachment:'deleted-question'}),false);
state=step(state,'resolve','paused');
state=step(state,'next');
assert.equal(state.chapter,2);
state=step(state,'advance');
assert.equal(step(state,'recovery-record','official-recovery'),state);
state=step(state,'inspect','recovery-team:official-help');
state=step(state,'recovery-record','official-recovery');
assert.ok(state.events.some(e=>e.type==='recovery-record'));
assert.equal(step(state,'recovery-record','official-recovery'),state);
assert.equal(totalSpent(state),0);
assert.deepEqual(restoreRun(serializeRun(state)),state);
console.log('Attachment branch regressions passed.');
