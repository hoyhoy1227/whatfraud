import assert from 'node:assert/strict';
import {createRun,transition,chapters,serializeRun,restoreRun} from '../app/story/engine.js';
import {buildResponseReport} from '../app/story/response-report.js';
const act=(s,type,data='')=>transition(s,{type,chapter:s.chapter,data});
let state=createRun();
assert.equal(buildResponseReport(state).cases.length,0);
state=act(state,'resolve','paused');
let report=buildResponseReport(state);
assert.equal(report.protectedCases,1);assert.equal(report.groundedCases,0);
assert.ok(report.cases[0].cautions.some(t=>t.includes('검증')));
assert.deepEqual(buildResponseReport(restoreRun(serializeRun(state))),report);
let checked=createRun();
for(const e of chapters[0].story.evidence)checked=act(checked,'inspect',chapters[0].id+':'+e.id);
checked=act(checked,'resolve','verified');
assert.equal(buildResponseReport(checked).groundedCases,1);
// Synthetic event order tests isolate reporting from progression fixtures.
const loss={...state,results:[{chapter:0,kind:'stopped',spent:80000,verified:false}],transactions:[{chapter:0,amount:80000}],events:[{chapter:0,type:'decision-result',data:'familiar-check:verify:recipient-note'},{chapter:0,type:'confirm',data:'familiar-request:main'},...checked.events.filter(e=>e.type==='inspect'),{chapter:0,type:'resolve',data:'stopped'}],inspected:checked.inspected};
report=buildResponseReport(loss);
assert.equal(report.groundedCases,0);assert.equal(report.spent,80000);
assert.ok(report.cases[0].cautions.some(t=>t.includes('그 뒤 실제 송금')));
assert.ok(report.cases[0].strengths.some(t=>t.includes('추가 요청을 중단')));
assert.ok(report.cases[0].dialogue.some(t=>t.includes('수취인 이름 메모')));
let demo=act(createRun('demo'),'resolve','paused');
assert.deepEqual(buildResponseReport(demo).cases.map(c=>c.index),[1]);
assert.ok(!JSON.stringify(buildResponseReport(demo)).includes('준호와의 대화'));
const unknown={...state,events:[{chapter:0,type:'decision-result',data:'x:unknown:none'},{chapter:0,type:'talk',data:'invented'}]};
assert.equal(buildResponseReport(unknown).cases[0].choices.length,0);
assert.equal(buildResponseReport(unknown).cases[0].dialogue.length,0);
console.log('Response report: completion scope, demo, event order, loss, dialogue limits and saved-run parity passed.');
